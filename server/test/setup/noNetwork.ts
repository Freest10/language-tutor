/**
 * Общая страховка тестов: ни один тест не ходит в сеть.
 *
 * Тесты сервера проверяют работу с провайдерами LLM/STT/TTS по подменённому
 * `fetch`. Забытая подмена раньше означала настоящий сетевой запрос: тест либо
 * висел до таймаута, либо (на поднятой локально Ollama) молча проходил на живой
 * модели. Заглушка ставится один раз на файл тестов и падает с внятным текстом;
 * `vi.stubGlobal('fetch', …)` её перекрывает, а `vi.unstubAllGlobals()`
 * возвращает именно её, а не настоящий `fetch`.
 */
const message =
  'Тест обратился в сеть: подмените fetch через vi.stubGlobal("fetch", …). ' +
  'Настоящие запросы к провайдерам из тестов запрещены.';

globalThis.fetch = (async (input: unknown): Promise<never> => {
  throw new Error(`${message} URL: ${String(input)}`);
}) as typeof fetch;

/**
 * Бюджет реплик шага урока: сколько раз ученик может ответить на шаге, прежде
 * чем сервер закроет его сам.
 *
 * Флага `stepComplete` от модели для этого недостаточно: локальная модель его
 * не ставит и продолжает спрашивать «а что ещё?» у ученика, который уже сказал,
 * что добавить ему нечего. Ученик при этом видит урок, который топчется на
 * месте, и понять, что происходит, не может. Бюджет — страховка, которая
 * не зависит от модели: шаг заканчивается не позже, чем исчерпает отведённое
 * планом время, если считать по репликам.
 *
 * Считать по репликам, а не по часам, надёжнее: урок бывает оставлен открытым на
 * перерыв, и шаг «длиной пять минут» по часам заканчивался бы ещё до первой
 * реплики после возвращения. Обмен репликами на голосовом уроке — озвучка
 * вопроса, ответ ученика, распознавание и ответ модели — занимает около двух
 * минут, отсюда и коэффициент.
 */

/** Сколько минут занимает один обмен репликами на голосовом уроке. */
export const MINUTES_PER_EXCHANGE = 2;

/**
 * Меньше этого числа реплик ученика шагу не отводится: даже на коротком шаге
 * тьютор должен успеть задать вопрос, уточнить и подвести итог.
 */
export const MIN_STEP_TURNS = 3;

/**
 * Больше этого числа реплик ученика шагу не отводится: на длинном шаге тема
 * исчерпывается раньше, чем время, и лучше перейти к следующей, чем добирать
 * минуты вопросами по кругу.
 */
export const MAX_STEP_TURNS = 8;

/** Сколько реплик ученика отведено шагу длительностью `estimatedMinutes` минут. */
export function stepTurnBudget(estimatedMinutes: number): number {
  const byTime = Math.round(estimatedMinutes / MINUTES_PER_EXCHANGE);

  return Math.min(MAX_STEP_TURNS, Math.max(MIN_STEP_TURNS, byTime));
}

/** Ход шага по репликам ученика: сколько уже сказано и сколько отведено. */
export interface StepPacing {
  /** Реплик ученика на шаге, включая ту, на которую тьютор отвечает сейчас. */
  learnerTurns: number;
  /** Сколько реплик ученика отведено шагу. */
  budget: number;
}

/** Сколько реплик ученика остаётся шагу после текущей; ноль и меньше — текущая последняя. */
export function turnsLeft(pacing: StepPacing): number {
  return pacing.budget - pacing.learnerTurns;
}

/** Исчерпан ли бюджет шага: текущая реплика ученика на нём — последняя. */
export function isBudgetSpent(pacing: StepPacing): boolean {
  return turnsLeft(pacing) <= 0;
}

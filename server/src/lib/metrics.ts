/**
 * Счётные помощники прогресса: доля верных ответов и её человекочитаемый вид.
 *
 * Долю считают и ход урока (итог занятия), и сводка прогресса, и автокоррекция
 * уровня. Формула одна на всех: разные способы округлить или поделить на ноль
 * дали бы разные цифры на одних и тех же данных.
 */

/** Доля верных ответов, 0..1; без попыток — 0, а не деление на ноль. */
export function accuracyRatio(correct: number, total: number): number {
  return total === 0 ? 0 : Math.min(1, Math.max(0, correct / total));
}

/** Доля 0..1 в процентах для человекочитаемых обоснований. */
export function formatPercent(value: number): string {
  return `${String(Math.round(value * 100))}%`;
}

/**
 * Общий интерфейс локального распознавания текста на изображении.
 *
 * Бэкендов два (macOS Vision и `tesseract`), и оба заменяемы: слой извлечения
 * знает только `recognize(путь, языки)`. Ни один из них не входит в приложение
 * как зависимость — это системные возможности, которых на машине может не быть,
 * поэтому `isAvailable()` обязателен и проверяется до начала работы.
 */

/** Локальный распознаватель текста на изображении. */
export interface OcrBackend {
  /** Имя для сообщений и логов: попадает в `statusMessage` материала. */
  readonly name: string;
  /** Доступен ли бэкенд на этой машине (платформа, установленные программы). */
  isAvailable(): Promise<boolean>;
  /**
   * Распознаёт текст на изображении.
   *
   * @param imagePath путь к PNG страницы
   * @param langs коды языков BCP-47 (`en-US`, `ru-RU`); бэкенд переводит их в свои
   * @returns распознанный текст; пустая строка — на изображении текста нет
   */
  recognize(imagePath: string, langs: readonly string[]): Promise<string>;
}
